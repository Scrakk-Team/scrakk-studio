/** Tipos de las preferencias experimentales de la Activity Bar. */

/** 'default' (arriba), 'centered' (centro) y 'wheel' (rueda 3D con scroll). */
export type ActivityBarMode = 'default' | 'centered' | 'wheel'

/** Qué barra lateral está desactivada ('none' = ambas activas). */
export type DisabledActivitySide = 'none' | 'left' | 'right'
